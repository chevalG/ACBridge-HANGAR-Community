import assert from 'node:assert/strict';
import {evaluate,emissions} from '../web/js/fxr-evaluate.mjs';
const linear={function:'Linear',loop:false,keyframes:[{position:0,value:[1,0,2,1]},{position:.2,value:[0,2,4,0]}]};
assert.deepEqual(evaluate(linear,.1),[.5,1,3,.5]);
evaluate({...linear,loop:true},.3).forEach((v,i)=>assert.ok(Math.abs(v-evaluate(linear,.1)[i])<1e-12));
assert.equal(evaluate({value:2,modifiers:[{type:'ExternalValue1',externalValue:40000,factor:{function:'Linear',keyframes:[{position:0,value:1},{position:100,value:3}]}}]},0,0,50),4);
assert.deepEqual(evaluate({...linear,modifiers:[{type:'ExternalValue1',externalValue:40000,factor:2}]},.1),[1,2,6,1]);
assert.equal(evaluate({function:'Stepped',keyframes:[{position:0,value:2},{position:.2,value:4}]},.1),2);
const fraction={value:5,modifiers:[{type:'RandomFraction',seed:17,max:.2}]};
assert.ok(evaluate(fraction,0,2)>=4&&evaluate(fraction,0,2)<=6);
const vectorRandom={value:[0,0,0],modifiers:[{type:'RandomRange',seed:[1,2,3],min:[0,0,0],max:[1,1,1]}]};
const channels=evaluate(vectorRandom,0,17);assert.equal(new Set(channels).size,3);assert.deepEqual(channels,evaluate(vectorRandom,5,17));
const random={value:.2,modifiers:[{type:'RandomRange',seed:3,min:0,max:.2}]};
assert.equal(evaluate(random,0,17),evaluate(random,4,17));
assert.notEqual(evaluate(random,0,17),evaluate(random,0,18));
assert.throws(()=>evaluate({value:1,modifiers:[{type:'ExternalValue1',externalValue:999,factor:1}]},0));
const config={nodeAttributes:{duration:.1,delay:.2},emitter:{type:300,interval:1/30,perEmission:1,totalEmissions:-1,maxConcurrent:6}};
assert.deepEqual(emissions(config,.199),[]);
assert.equal(emissions(config,.25).length,2);
assert.equal(emissions(config,.7).length,3);
assert.deepEqual(emissions(config,.25),emissions(config,.25));
assert.deepEqual(emissions({...config,emitter:{type:399}},.25),[{birth:.2,index:0}]);
console.log('PASS original scalar/vector curves, deterministic modifiers, external input, absolute emission schedule');
